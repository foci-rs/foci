"""Generate the commissioning vocabulary (Rust enums + host Python tables) from
vocabulary.toml. Single source of truth; do not hand-edit the outputs."""

from __future__ import annotations

import argparse
import json
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = ROOT / "shared/foci-firmware/src/commissioning/vocabulary.toml"
RUST_OUT = ROOT / "shared/foci-firmware/src/commissioning/vocabulary_generated.rs"
KLIPPER_OUT = ROOT / "host/klipper-foci/_vocabulary_generated.py"
TRACE_OUT = ROOT / "host/foci-trace/foci_trace/_vocabulary_generated.py"

RUST_HEADER = (
    "// @generated by tools/gen_commissioning_vocabulary.py from vocabulary.toml. Do not edit.\n\n"
)
PY_HEADER = (
    '"""@generated by tools/gen_commissioning_vocabulary.py from vocabulary.toml. '
    'Do not edit."""\n\n'
)
DERIVE = "#[derive(Debug, Clone, Copy, PartialEq, Eq, defmt::Format)]"

